void showElerozHelpDialog() {
  var selected = 0;

  gFFI.dialogManager.show((setState, close, context) {
    final section = _sections[selected];
    final navColor = Theme.of(context).colorScheme.background;

    return CustomAlertDialog(
      title: Row(
        children: [
          Icon(Icons.help_outline, color: MyTheme.accent),
          const Text('Инструкция').paddingOnly(left: 10),
        ],
      ),
      contentBoxConstraints: const BoxConstraints(maxWidth: 780),
      content: SizedBox(
        width: 740,
        height: 420,
        child: Row(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            Container(
              width: 220,
              color: navColor,
              child: ListView.builder(
                itemCount: _sections.length,
                itemBuilder: (_, index) {
                  final active = index == selected;
                  return InkWell(
                    onTap: () => setState(() => selected = index),
                    child: Container(
                      padding:
                          const EdgeInsets.symmetric(horizontal: 14, vertical: 12),
                      decoration: BoxDecoration(
                        border: Border(
                          left: BorderSide(
                            width: 3,
                            color: active ? MyTheme.accent : Colors.transparent,
                          ),
                        ),
                      ),
                      child: Text(
                        _sections[index].title,
                        style: TextStyle(
                          fontSize: 14,
                          fontWeight: active ? FontWeight.w600 : FontWeight.normal,
                          color: active ? MyTheme.accent : null,
                        ),
                      ),
                    ),
                  );
                },
              ),
            ),
            Expanded(
              child: SingleChildScrollView(
                padding: const EdgeInsets.only(left: 20, right: 4),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      section.title,
                      style: const TextStyle(
                          fontSize: 18, fontWeight: FontWeight.w600),
                    ),
                    Text(
                      section.intro,
                      style: const TextStyle(fontSize: 14, height: 1.45),
                    ).marginOnly(top: 8, bottom: 4),
                    for (final item in section.items)
                      Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Text(
                            item.title,
                            style: const TextStyle(
                                fontSize: 14.5, fontWeight: FontWeight.w600),
                          ).marginOnly(top: 14),
                          Text(
                            item.text,
                            style: const TextStyle(fontSize: 14, height: 1.45),
                          ).marginOnly(top: 4),
                        ],
                      ),
                  ],
                ),
              ),
            ),
          ],
        ),
      ),
      actions: [dialogButton('Закрыть', onPressed: close)],
      onCancel: close,
    );
  });
}
